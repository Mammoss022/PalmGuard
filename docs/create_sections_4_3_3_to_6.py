"""Generate report sections using the author's draft and saved evaluation."""
import json
from pathlib import Path
from docx import Document
from docx.shared import Cm, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT.parent / 'ai/models/evaluation-v1.3.json').read_text(encoding='utf-8'))
doc = Document(ROOT / 'PalmGuard_section_4.3.2.docx')
for element in list(doc.element.body):
    if element.tag != qn('w:sectPr'):
        doc.element.body.remove(element)

def p(text, indent=True):
    paragraph = doc.add_paragraph(text)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent:
        paragraph.paragraph_format.first_line_indent = Cm(1.25)
    return paragraph

def heading(text):
    paragraph = p(text, False)
    paragraph.runs[0].bold = True
    paragraph.paragraph_format.keep_with_next = True

def table(caption, headers, rows):
    paragraph = p(caption, False)
    paragraph.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=0, cols=len(headers))
    t.style = 'Table Grid'
    for index, values in enumerate([headers] + rows):
        row = t.add_row()
        row._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
        if index == 0:
            row._tr.get_or_add_trPr().append(OxmlElement('w:tblHeader'))
        for cell, value in zip(row.cells, values):
            cell.text = str(value)
            for paragraph in cell.paragraphs:
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                paragraph.paragraph_format.space_after = Pt(3)
                paragraph.paragraph_format.space_before = Pt(3)
                for run in paragraph.runs:
                    run.font.size = Pt(14)
                    run.bold = index == 0
            if index == 0:
                shade = OxmlElement('w:shd')
                shade.set(qn('w:fill'), 'D9D9D9')
                cell._tc.get_or_add_tcPr().append(shade)
    return t

def image(name, caption):
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.keep_with_next = True
    paragraph.add_run().add_picture(str(ROOT / 'report-figures' / name), width=Cm(15.3))
    paragraph = doc.add_paragraph(caption)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER

def metrics_table(key, number, label):
    report = data[key]['report']
    rows = []
    for code, name in [('brown_spots', 'ใบจุดสีน้ำตาล'), ('healthy', 'ใบปกติ'), ('white_scale', 'เพลี้ยหอย')]:
        item = report[code]
        rows.append([name, int(item['support']), f"{report['accuracy']*100:.2f}", *[f"{item[k]*100:.2f}" for k in ['precision','recall','f1-score']]])
    table(f'ตารางที่ {number} ผลการจำแนกประเภทใบปาล์มบนชุดทดสอบข้อมูล{label}',
          ['ประเภท', 'จำนวน\n(ภาพ)', 'Accuracy\n(%)', 'Precision\n(%)', 'Recall\n(%)', 'F1-Score\n(%)'], rows)
    note = p('หมายเหตุ: Accuracy เป็นค่ารวมของชุดทดสอบ โดยแสดงค่าเดียวกันในทุกแถว ส่วน Precision, Recall และ F1-Score เป็นค่าของแต่ละประเภท', False)
    for run in note.runs:
        run.font.size = Pt(14)

